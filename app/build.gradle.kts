// 签名信息放在 keystore.properties（不入库）。缺这个文件时 release 退回 debug 签名，
// 保证 clone 下来的人也能 assembleRelease 出包，只是不能覆盖安装已发布的版本。
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) FileInputStream(keystorePropsFile).use { load(it) }
}
val hasReleaseKey = keystorePropsFile.exists()

android {
    namespace = "com.airu.gametodo"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.airu.gametodo"
        minSdk = 26
        targetSdk = 35
        // 版本号：大版本.小版本.迭代序列（大版本=大型更新/重构，小版本=对外发包，迭代序列=每次打包递增）
        // versionCode = 大*10000 + 小*100 + 迭代，保证单调递增
        versionCode = 10001
        versionName = "1.0.1"
    }

    signingConfigs {
        create("release") {
            if (hasReleaseKey) {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // 先不混淆：Room/Compose 混起来要额外验证，等确实需要压体积再开
            isMinifyEnabled = false
            isShrinkResources = false
            signingConfig =
                if (hasReleaseKey) signingConfigs.getByName("release") else signingConfigs.getByName("debug")
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

